#!/usr/bin/env python3
"""Order-scene voice pipeline: TTS -> audio files -> local STT -> intent -> manifest.

Run from the repository root::

    python -m barista.voice.pipeline --out OUT_DIR                 # placeholder-local voices
    python -m barista.voice.pipeline --out OUT_DIR --provider fish_audio --allow-spend  # A3b

Writes ``OUT_DIR/audio/<line id>.wav`` and ``OUT_DIR/manifest.json`` (schema
``jumper-barista-voice/1``, documented in ``barista/voice/README.md``). The customer line's
``transcript`` is whisper.cpp's output on that line's audio file, never the script text;
``intent`` is parsed from that transcript. Exit status: 0 when the customer transcript
matches the script up to normalisation and every expected intent is met, 2 when a check
fails, 3 when a paid provider refuses to spend (no key, no --allow-spend, wallet credit too
low, or the $3 cap would be exceeded; all checked before the first request).

With several candidates per request (Fish Audio Voice Design returns up to 4 for one
billed request), a jumper line keeps candidate 0; the customer line keeps the first
candidate, in index order, whose own whisper.cpp transcript parses to the expected intent
(candidate 0 if none does). Every candidate's transcript is recorded in the manifest.

Generated audio is an artefact: keep OUT_DIR outside the repository (or untracked).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

from . import intent as intent_mod
from . import providers, stt

SCRIPT = Path(__file__).resolve().parent / "script.json"
SCHEMA = "jumper-barista-voice/1"
EYE_EXPRESSIONS = ("neutral", "surprised", "listening", "happy", "wink")
SIMULATION_NOTE = (
    "Synthetic voices for a MuJoCo simulation film, generated by a TTS provider (see "
    "`provider`). The real robot has no speaker pipeline and did not do this."
)
LINE_KEYS = ("id", "speaker", "text", "audio_path", "duration_s", "sample_rate", "provider",
             "transcript", "intent", "eye_expression", "eye_keyframes")


def eye_keyframes(line: dict, duration_s: float) -> list[list]:
    """``[[t_s, expression], ...]`` relative to the line's start; an end expression (the
    confirm line's wink) takes the last ``eye_end_lead_s`` seconds of the audio."""
    frames: list[list] = [[0.0, line["eye_expression"]]]
    end = line.get("eye_expression_end")
    if end:
        lead = float(line.get("eye_end_lead_s", 0.6))
        frames.append([round(max(0.0, duration_s - lead), 4), end])
    return frames


def validate_manifest(manifest: dict, root: Path | None = None) -> list[str]:
    """Return the list of contract violations (empty when valid)."""
    errors = []
    if manifest.get("schema") != SCHEMA:
        errors.append(f"schema is {manifest.get('schema')!r}")
    lines = manifest.get("lines") or []
    if not lines:
        errors.append("no lines")
    for line in lines:
        missing = [key for key in LINE_KEYS if key not in line]
        if missing:
            errors.append(f"{line.get('id')}: missing {missing}")
            continue
        if line["speaker"] == "customer":
            if not isinstance(line["transcript"], str) or not line["intent"]:
                errors.append(f"{line['id']}: customer line needs transcript and intent")
        elif line["transcript"] is not None or line["intent"] is not None:
            errors.append(f"{line['id']}: jumper lines carry no transcript/intent")
        frames = line["eye_keyframes"]
        if not frames or frames[0] != [0.0, line["eye_expression"]]:
            errors.append(f"{line['id']}: eye_keyframes must start with eye_expression")
        for t, name in frames:
            if name not in EYE_EXPRESSIONS or not 0.0 <= t <= line["duration_s"]:
                errors.append(f"{line['id']}: bad eye keyframe {[t, name]}")
        if not line["duration_s"] > 0 or not line["sample_rate"] > 0:
            errors.append(f"{line['id']}: empty audio")
        if root is not None and not (root / line["audio_path"]).is_file():
            errors.append(f"{line['id']}: {line['audio_path']} missing")
    if manifest.get("passes") is not (
        bool(manifest.get("checks")) and all(c["pass"] for c in manifest["checks"])
    ):
        errors.append("passes disagrees with checks")
    return errors


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def select_lines(
    script: dict, include_optional: list[str], alternatives: list[str]
) -> list[dict]:
    lines = [dict(line) for line in script["lines"]]
    for extra_id in include_optional:
        extra = next((x for x in script.get("optional_lines", []) if x["id"] == extra_id), None)
        if extra is None:
            raise ValueError(f"no optional line {extra_id!r}")
        after = next(i for i, line in enumerate(lines) if line["id"] == extra["after"])
        lines.insert(after + 1, dict(extra))
    for line_id in alternatives:
        line = next((x for x in lines if x["id"] == line_id), None)
        if line is None or not line.get("alternatives"):
            raise ValueError(f"line {line_id!r} has no alternative text")
        line["text"] = line["alternatives"][0]
    for line in lines:
        if line["speaker"] not in ("customer", "jumper"):
            raise ValueError(f"line {line['id']!r}: unknown speaker {line['speaker']!r}")
        if line["eye_expression"] not in EYE_EXPRESSIONS:
            raise ValueError(f"line {line['id']!r}: unknown eye {line['eye_expression']!r}")
    return lines


def run(
    out: Path,
    provider_name: str = "placeholder-local",
    allow_spend: bool = False,
    stt_model: Path | None = None,
    script_path: Path = SCRIPT,
    include_optional: list[str] | None = None,
    alternatives: list[str] | None = None,
    provider_kwargs: dict | None = None,
) -> dict:
    script_bytes = script_path.read_bytes()
    script = json.loads(script_bytes)
    lines = select_lines(script, include_optional or [], alternatives or [])
    provider = providers.get_provider(provider_name, allow_spend=allow_spend,
                                      **(provider_kwargs or {}))
    provider.ensure_allowed()  # a paid provider refuses here, before any file or STT work
    wallet_before = provider.preflight(len(lines))  # credit + cap, before any request
    voices = script["voices"][provider_name]
    recogniser = stt.WhisperCpp(stt_model)
    out.mkdir(parents=True, exist_ok=True)
    manifest_lines = []
    checks = []
    for line in lines:
        rel = Path("audio") / f"{line['id']}.wav"
        audio = provider.synthesize(line["text"], voices[line["speaker"]], out / rel,
                                    line_id=line["id"])
        generation = dict(provider.last_generation) if provider.last_generation else None
        heard = []
        if line["speaker"] == "customer":
            expected = line.get("expected_intent") or {}
            for index, candidate in enumerate(provider.candidates):
                transcript = recogniser.transcribe(candidate.path)
                parsed = intent_mod.parse_intent(transcript.text)
                heard.append({"candidate": index, "audio": candidate.path.name,
                              "transcript": transcript.text, "intent": parsed,
                              "duration_s": candidate.duration_s})
            chosen = next((h["candidate"] for h in heard if all(
                h["intent"].get(k) == v for k, v in expected.items())), 0)
            if chosen:
                shutil.copyfile(provider.candidates[chosen].path, out / rel)
                audio = providers.wav_info(out / rel)
                if generation:
                    generation["candidate_index"] = chosen
        entry = {
            "id": line["id"],
            "speaker": line["speaker"],
            "text": line["text"],
            "audio_path": rel.as_posix(),
            "duration_s": audio.duration_s,
            "sample_rate": audio.sample_rate,
            "provider": provider.name,
            "transcript": None,
            "intent": None,
            "eye_expression": line["eye_expression"],
            "eye_keyframes": eye_keyframes(line, audio.duration_s),
            "audio_sha256": _sha256(out / rel),
            "generation": generation,
        }
        if line["speaker"] == "customer":
            transcript = recogniser.transcribe(out / rel)
            entry["stt_candidates"] = heard
            entry["transcript"] = transcript.text
            entry["intent"] = intent_mod.parse_intent(transcript.text)
            matches = intent_mod.normalise(transcript.text) == intent_mod.normalise(line["text"])
            checks.append({
                "line": line["id"], "check": "transcript_matches_script_normalised",
                "pass": matches,
                "normalised_transcript": intent_mod.normalise(transcript.text),
                "normalised_script": intent_mod.normalise(line["text"]),
            })
            expected = line.get("expected_intent")
            if expected:
                ok = all(entry["intent"].get(key) == value for key, value in expected.items())
                checks.append({"line": line["id"], "check": "intent", "pass": ok,
                               "expected": expected, "observed": entry["intent"]})
        manifest_lines.append(entry)
    manifest = {
        "schema": SCHEMA,
        "simulation_note": SIMULATION_NOTE,
        "script_sha256": hashlib.sha256(script_bytes).hexdigest(),
        "provider": provider.name,
        "stt": {
            "engine": recogniser.engine,
            "engine_version": recogniser.version,
            "model": recogniser.model.name,
            "model_sha256": recogniser.model_sha256,
        },
        "lines": manifest_lines,
        "checks": checks,
        "passes": all(check["pass"] for check in checks) and bool(checks),
    }
    if provider.paid:
        wallet_after = provider.wallet()
        run_usd = round(sum((x["generation"] or {}).get("usd", 0) for x in manifest_lines), 6)
        manifest["spend"] = {
            "wallet_before": wallet_before,
            "wallet_after": wallet_after,
            "usd_this_run_ledger": run_usd,
            "usd_this_run_wallet_delta": round(
                wallet_before["credit_usd"] - wallet_after["credit_usd"], 6),
            "usd_cumulative_ledger": provider.ledger.total_usd(),
            "cap_usd": provider.ledger.cap_usd,
        }
    (out / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", "utf-8"
    )
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--provider", default="placeholder-local",
                        choices=sorted(providers.PROVIDERS))
    parser.add_argument("--allow-spend", action="store_true",
                        help="permit a paid provider to generate (Mattia's gate; needs a key)")
    parser.add_argument("--stt-model", type=Path, default=None)
    parser.add_argument("--script", type=Path, default=SCRIPT)
    parser.add_argument("--include-optional", action="append", default=[], metavar="ID")
    parser.add_argument("--use-alternative", action="append", default=[], metavar="ID")
    args = parser.parse_args(argv)
    try:
        manifest = run(
            args.out.resolve(), args.provider, args.allow_spend, args.stt_model, args.script,
            args.include_optional, args.use_alternative,
        )
    except providers.SpendRefused as refused:
        print(f"[voice] refused: {refused}", file=sys.stderr)
        return 3
    for line in manifest["lines"]:
        heard = f" | heard: {line['transcript']!r} -> {line['intent']['drink']}" if (
            line["transcript"] is not None) else ""
        print(f"[voice] {line['id']:8s} {line['speaker']:8s} {line['duration_s']:6.2f}s "
              f"eyes={line['eye_expression']:9s} {line['text']!r}{heard}")
    for check in manifest["checks"]:
        print(f"[voice] check {check['line']}/{check['check']}: pass={check['pass']}")
    print(f"[voice] stt: {manifest['stt']['engine']} {manifest['stt']['engine_version']} "
          f"{manifest['stt']['model']}")
    if "spend" in manifest:
        spend = manifest["spend"]
        print(f"[voice] spend: ledger ${spend['usd_this_run_ledger']:.4f} this run, "
              f"wallet ${spend['wallet_before']['credit_usd']:.4f} -> "
              f"${spend['wallet_after']['credit_usd']:.4f}, cumulative "
              f"${spend['usd_cumulative_ledger']:.4f} / cap ${spend['cap_usd']:.2f}")
    errors = validate_manifest(manifest, args.out.resolve())
    for error in errors:
        print(f"[voice] manifest invalid: {error}", file=sys.stderr)
    print(f"[voice] manifest: {args.out.resolve() / 'manifest.json'} passes={manifest['passes']}")
    return 0 if manifest["passes"] and not errors else 2


if __name__ == "__main__":
    raise SystemExit(main())
