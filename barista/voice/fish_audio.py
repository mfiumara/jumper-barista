"""Fish Audio client for A3b: wallet read, Voice Design generation and a hard spend cap.

Mattia's gate (t_0bfa02ac, 2026-10-11): Fish Audio pay-as-you-go, **usage cap $3**, designed
voices only (no Voice Library, no cloning). Each scene line is generated by one
``POST /v1/voice-design`` request (``voice-design-1``, $0.01 per successful request, however
many candidates it returns) with the approved instruction, a fixed seed and the line as
``reference_text``; no reference audio is ever uploaded and no voice model is created.

Spend control, all enforced *before* a request is sent:

* :class:`SpendLedger` is a JSON file of every billed request (numbers only). A request is
  refused when ``ledger total + this request's price > cap``.
* :func:`preflight` reads the wallet (``GET /wallet/self/api-credit``, free) and refuses when
  the credit cannot cover the planned batch (a credit of 0 always refuses).

The API key is passed in by the caller, used only in the ``Authorization`` header and never
printed, logged, stored or included in an exception message. Wallet reads return only the
numeric ``credit`` and ``cumulative_top_up`` fields.
"""

from __future__ import annotations

import base64
import json
import time
import urllib.error
import urllib.request
from dataclasses import dataclass
from pathlib import Path

API = "https://api.fish.audio"
VOICE_DESIGN_MODEL = "voice-design-1"
# https://docs.fish.audio/developer-guide/models-pricing/pricing-and-rate-limits (2026-10-11)
PRICE_USD = {
    "voice-design-1": {"per_request": 0.01},
    "s2.1-pro": {"per_utf8_byte": 15.00 / 1_000_000},
    "s2.1-pro-free": {"per_utf8_byte": 0.0},
}
CAP_USD = 3.00
LEDGER = Path(__file__).resolve().parent / "fish_audio_spend.json"
TIMEOUT_S = 180


class SpendCapExceeded(RuntimeError):
    """A request would push cumulative Fish Audio usage over the approved cap."""


class FishAudioError(RuntimeError):
    """A non-2xx API response. Carries the status and the server message, never the key."""

    def __init__(self, status: int, message: str) -> None:
        super().__init__(f"Fish Audio HTTP {status}: {message}")
        self.status = status


def request_price(model: str, text: str = "") -> float:
    price = PRICE_USD[model]
    if "per_request" in price:
        return price["per_request"]
    return len(text.encode("utf-8")) * price["per_utf8_byte"]


class SpendLedger:
    """Append-only record of billed requests; the cap is checked against its total."""

    def __init__(self, path: Path = LEDGER, cap_usd: float = CAP_USD) -> None:
        self.path = Path(path)
        self.cap_usd = float(cap_usd)

    def entries(self) -> list[dict]:
        if not self.path.is_file():
            return []
        return json.loads(self.path.read_text("utf-8"))["requests"]

    def total_usd(self) -> float:
        return round(sum(float(entry["usd"]) for entry in self.entries()), 6)

    def check(self, usd: float) -> None:
        total = self.total_usd()
        if total + usd > self.cap_usd + 1e-9:
            raise SpendCapExceeded(
                f"refusing: cumulative ${total:.4f} + this request ${usd:.4f} would exceed "
                f"the approved ${self.cap_usd:.2f} cap"
            )

    def record(self, entry: dict) -> None:
        entries = self.entries() + [entry]
        self.path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "provider": "fish_audio",
            "cap_usd": self.cap_usd,
            "total_usd": round(sum(float(e["usd"]) for e in entries), 6),
            "requests": entries,
        }
        self.path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", "utf-8")


def _call(method: str, path: str, key: str, body: dict | None = None,
          headers: dict | None = None, opener=urllib.request.urlopen) -> dict:
    data = None if body is None else json.dumps(body).encode("utf-8")
    request = urllib.request.Request(API + path, data=data, method=method)
    request.add_header("Authorization", "Bearer " + key)
    if data is not None:
        request.add_header("Content-Type", "application/json")
    for name, value in (headers or {}).items():
        request.add_header(name, value)
    try:
        with opener(request, timeout=TIMEOUT_S) as response:
            return json.loads(response.read())
    except urllib.error.HTTPError as error:
        raw = error.read()[:500].decode("utf-8", errors="replace")
        try:
            message = json.loads(raw).get("message", raw)
        except ValueError:
            message = raw
        raise FishAudioError(error.code, str(message)) from None


def read_wallet(key: str, opener=urllib.request.urlopen) -> dict:
    """Free read of the API credit; returns only the numbers (USD)."""
    body = _call("GET", "/wallet/self/api-credit", key, opener=opener)
    return {
        "credit_usd": float(body.get("credit") or 0),
        "cumulative_top_up_usd": float(body.get("cumulative_top_up") or 0),
        "read_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }


def preflight(key: str, planned_usd: float, ledger: SpendLedger,
              opener=urllib.request.urlopen) -> dict:
    """Wallet must cover the batch and the batch must fit under the cap. Returns the wallet."""
    wallet = read_wallet(key, opener=opener)
    if wallet["credit_usd"] <= 0 or wallet["credit_usd"] + 1e-9 < planned_usd:
        raise SpendCapExceeded(
            f"refusing: Fish Audio API credit is ${wallet['credit_usd']:.4f}, the planned "
            f"batch needs ${planned_usd:.4f}; top up (one top-up <= $5, no auto-recharge)"
        )
    ledger.check(planned_usd)
    return wallet


@dataclass(frozen=True)
class Candidate:
    index: int
    id: str
    wav_bytes: bytes
    sample_rate: int
    duration_ms: int


def voice_design(key: str, instruction: str, reference_text: str, *, seed: int, n: int = 1,
                 language: str | None = None, speed: float = 1.0, num_step: int = 32,
                 guidance_scale: float = 2.0, ledger: SpendLedger,
                 meta: dict | None = None,
                 opener=urllib.request.urlopen) -> list[Candidate]:
    """One billed ``voice-design-1`` request; records it in the ledger after success."""
    usd = request_price(VOICE_DESIGN_MODEL)
    ledger.check(usd)
    body = {
        "instruction": instruction,
        "reference_text": reference_text,
        "language": language,
        "n": int(n),
        "speed": float(speed),
        "num_step": int(num_step),
        "guidance_scale": float(guidance_scale),
        "seed": int(seed),
    }
    payload = _call("POST", "/v1/voice-design", key, body,
                    headers={"model": VOICE_DESIGN_MODEL}, opener=opener)
    candidates = [
        Candidate(
            index=int(item.get("index", i)),
            id=str(item.get("id", "")),
            wav_bytes=base64.b64decode(item["audio_base64"]),
            sample_rate=int(item["sample_rate"]),
            duration_ms=int(item["duration_ms"]),
        )
        for i, item in enumerate(payload.get("candidates") or [])
    ]
    if not candidates:  # empty responses are not billed (docs); nothing to record
        raise FishAudioError(200, "voice-design returned no candidates")
    ledger.record({
        "at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "endpoint": "POST /v1/voice-design",
        "model": VOICE_DESIGN_MODEL,
        "usd": usd,
        "reference_text_utf8_bytes": len(reference_text.encode("utf-8")),
        "candidates": len(candidates),
        "seed": int(seed),
        **(meta or {}),
    })
    return sorted(candidates, key=lambda c: c.index)
